function buildAdminRolePermissions(roleName) {
  const preset = ADMIN_ROLE_PERMISSIONS[roleName] || {}
  return ADMIN_PERMISSION_MODULES.map((module) => {
    const granted = preset[module] || []
    return {
      module,
      ...ADMIN_PERMISSION_ACTIONS.reduce((acc, action) => {
        acc[action] = granted.includes(action)
        return acc
      }, {}),
    }
  })
}

